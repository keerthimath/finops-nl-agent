#!/usr/bin/env python3
"""Generate the KQL that enforces subscription-level row security in ADX.

    python scripts/gen_rls.py scripts/teams.yaml > rls.kql

Review the output, run it against a NON-PROD database first. To run the steps with safety checks instead of
pasting them by hand, use scripts/rls_runbook.py.
"""
from __future__ import annotations

import re
import sys
from dataclasses import dataclass

import yaml

PRINCIPAL = re.compile(r"^(aaduser|aadgroup|aadapp)=[^'\"\s]+$")
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


@dataclass(frozen=True)
class Plan:
    table: str
    table_db: str
    fn: str
    col: str
    viewer_dbs: tuple[str, ...]
    allow_all: tuple[str, ...]
    teams: tuple[dict, ...]


def _check_principal(p: str) -> str:
    if not isinstance(p, str) or not PRINCIPAL.fullmatch(p):
        raise ValueError(f"Bad principal '{p}'. Use aaduser=..., aadgroup=<objectId>;<tenantId>, or aadapp=<appId>;<tenantId>.")
    return p


def _slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_") or "team"


def plan_from_config(cfg: dict) -> Plan:
    table = cfg["table"]
    fn = cfg.get("function_name", "FinopsRls_Costs")
    col = cfg.get("subscription_column", "SubAccountId")
    legacy_db = cfg.get("database", "Hub")
    table_db = cfg.get("table_database") or legacy_db
    viewer_dbs = tuple(cfg.get("viewer_databases") or [legacy_db])
    for ident in (table, fn, col, table_db, *viewer_dbs):
        if not IDENT.match(ident):
            raise ValueError(f"Bad identifier '{ident}'")
    allow_all = tuple(_check_principal(p) for p in cfg.get("allow_all", []))
    if not allow_all:
        raise ValueError("allow_all must include at least the FinOps admins and the ingestion identity, "
                         "otherwise enabling RLS will hide all rows from them (and break ingestion reads).")
    teams = []
    seen: set[str] = set()
    for t in cfg.get("teams", []):
        slug = _slug(t["name"])
        if slug in seen:
            raise ValueError(f"Duplicate team name '{t['name']}'")
        seen.add(slug)
        subs = [s.strip().lower() for s in t["subscriptions"]]
        if not subs or any(("'" in s or '"' in s) for s in subs):
            raise ValueError(f"Team '{t['name']}' needs a clean, non-empty subscription list")
        principals = t.get("principals")
        if principals is None:
            principals = [t.get("principal")]
        if not isinstance(principals, list) or not principals:
            raise ValueError(f"Team '{t['name']}' needs a non-empty principals list")
        principals = tuple(dict.fromkeys(_check_principal(principal) for principal in principals))
        teams.append({"slug": slug, "name": t["name"], "principals": principals, "subs": subs})
    return Plan(table, table_db, fn, col, viewer_dbs, allow_all, tuple(teams))


def function_command(p: Plan) -> str:
    lines = [f'.create-or-alter function with (folder="security", docstring="Subscription scoping for FinOps Hub") {p.fn}() {{']
    lines.append("    let allow_all = current_principal_is_member_of(" + ", ".join(f"'{a}'" for a in p.allow_all) + ");")
    names = []
    for t in p.teams:
        arr = ", ".join(f'"{s}"' for s in t["subs"])
        principals = ", ".join(f"'{principal}'" for principal in t["principals"])
        lines.append(f"    let sub_{t['slug']} = iff(current_principal_is_member_of({principals}), dynamic([{arr}]), dynamic([]));")
        names.append(f"sub_{t['slug']}")
    lines.append("    let allowed = array_concat(" + ", ".join(names) + ");" if names else "    let allowed = dynamic([]);")
    lines.append(f"    {p.table}")
    lines.append(f"    | where allow_all or set_has_element(allowed, tolower({p.col}))")
    lines.append("}")
    return "\n".join(lines)


def enable_command(p: Plan) -> str:
    return f'.alter table {p.table} policy row_level_security enable "{p.fn}()"'


def disable_command(p: Plan) -> str:
    return f'.alter table {p.table} policy row_level_security disable "{p.fn}()"'


def grant_commands(p: Plan) -> list[tuple[str, str]]:
    principals = dict.fromkeys(principal for team in p.teams for principal in team["principals"])
    return [(db, f".add database ['{db}'] viewers ('{principal}')")
            for db in p.viewer_dbs for principal in principals]


def generate(cfg: dict) -> str:
    p = plan_from_config(cfg)
    out: list[str] = []
    w = out.append
    w("// Generated by scripts/gen_rls.py - review before running.")
    w(f"// Steps 1-2 run in database: {p.table_db}")
    w("// 1) Row-level security function: each team sees only its subscriptions.")
    w(function_command(p))
    w("")
    w("// 2) Turn it on. From this point, every query on the table is filtered for every principal.")
    w(enable_command(p))
    w("")
    w("// 3) Database access: viewers only. Users do not need (and must not get) higher roles.")
    for db, cmd in grant_commands(p):
        w(f"// in database {db}:")
        w(cmd)
    w("")
    w("// --- Verify (run as a member of one team, then as an admin) ---")
    w("// Before enabling, check the blockers (RLS cannot be enabled if any of these apply):")
    w(f"//   .show table {p.table} policy update                  // referenced by an update policy not using a managed identity")
    w(f"//   .show table {p.table} policy restricted_view_access   // restricted view access policy must be off")
    w("//   .show materialized-views                            // views over this table need their own RLS or allowMaterializedViewsWithoutRowLevelSecurity")
    w(f"// .show table {p.table} policy row_level_security")
    w(f"// {p.table} | summarize by {p.col}     // team member: only their subscriptions")
    w("// --- Roll back ---")
    w("// " + disable_command(p))
    return "\n".join(out) + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    with open(sys.argv[1], encoding="utf-8") as f:
        cfg = yaml.safe_load(f)
    sys.stdout.write(generate(cfg))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
